#!/bin/bash
# Regenerate app/seed/demo-data.sql from the local development database.
#
#   scripts/make-snapshot.sh [database]      (default: listings_dev)
#
# Leaves out everything private-shaped — sessions, login codes, reports, saved
# items, message threads, votes — and the demo account, which the app creates
# itself. The result is plain INSERTs the demo loads on first boot
# (app/lib/snapshot.mjs). Re-run it after changing the sample data.
set -euo pipefail
DB="${1:-listings_dev}"
OUT="$(cd "$(dirname "$0")/.." && pwd)/app/seed/demo-data.sql"
mkdir -p "$(dirname "$OUT")"
{
  echo "-- WeZJUers demo data. Generated by scripts/make-snapshot.sh — do not edit."
  echo "-- snapshot-at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  pg_dump "$DB" --data-only --column-inserts --no-owner --no-privileges \
    -t campus -t category -t language -t board -t '"user"' -t user_language \
    -t listing -t listing_image -t post -t comment -t event -t event_signup \
  | grep -v "demo@wezjuers.invalid" \
  | grep -vE '^\\(un)?restrict '   # pg_dump 17+ psql-only lines
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes, $(grep -c '^INSERT' "$OUT") rows)"
