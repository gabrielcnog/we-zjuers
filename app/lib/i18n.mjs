const DICT = { en: EN, zh: ZH };
export function translator(locale) {
  const d = DICT[locale] || EN;
  return (key, ...args) => {
    const v = d[key] ?? EN[key] ?? key;
    return typeof v === 'function' ? v(...args) : v;
  };
}
/* Missing-key guard: the two dictionaries must stay identical in shape. */
export function missingKeys() {
  const a = Object.keys(EN), b = new Set(Object.keys(ZH));
  return a.filter((k) => !b.has(k));
}

/* The rolling search hint is animated by a hand-written @keyframes with one
   step per term, so the list length is load-bearing: change it in one locale
   and the roll drifts out of sync silently. This fails loudly instead. */
export const SEARCH_TERM_COUNT = 8;
export function termCountProblems() {
  const out = [];
  for (const [name, d] of [['en', EN], ['zh', ZH]])
    for (const key of ['search.terms', 'com.search.terms', 'guide.search.terms', 'ev.search.terms'])
      if (d[key].length !== SEARCH_TERM_COUNT)
        out.push(`${name} ${key} has ${d[key].length} terms, keyframes expect ${SEARCH_TERM_COUNT}`);
  return out;
}
